/** The name each generated type gets, and the schema it is generated from. */
const wanted = {
  RunInput: RunInputSchema,
  Policy: PolicySchema,
  PolicyRule: PolicyRuleSchema,
  PolicyInput: PolicyInputSchema,
  DocumentSearch: DocumentSearchSchema,
  DocumentSettings: DocumentSettingsSchema,
  MemoryRetrievalSettings: MemoryRetrievalSettingsSchema,
  AuditEntryInput: AuditEntrySchema,
  AuditQuery: AuditQuerySchema,
  CategoryDecisions: CategoryDecisionsSchema,
  AskFirstSettings: AskFirstSettingsSchema,
  AskFirstRequest: AskFirstRequestSchema,
  AskFirstAnswers: AnswersSchema,
  ClarifyingQuestion: ClarifyingQuestionSchema,
  RerankSettings: RerankSettingsSchema,
  PracticeSwitch: PracticeSwitchSchema,
  ProviderPresetInput: ProviderPresetInputSchema,
  IssueLink: IssueLinkSchema,
};

/** One JSON Schema written as TypeScript. Only the shapes the app's schemas actually produce. */
function toType(schema, indent = "  ") {
  if (!schema || typeof schema !== "object") return "unknown";
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  for (const key of ["anyOf", "oneOf"])
    if (Array.isArray(schema[key])) return schema[key].map((part) => toType(part, indent)).join(" | ");
  if (Array.isArray(schema.allOf)) return schema.allOf.map((part) => toType(part, indent)).join(" & ");
  const type = Array.isArray(schema.type) ? schema.type[0] : schema.type;
  if (type === "array") return `${wrap(toType(schema.items ?? {}, indent))}[]`;
  if (type === "string") return "string";
  if (type === "number" || type === "integer") return "number";
  if (type === "boolean") return "boolean";
  if (type === "null") return "null";
  if (type === "object" || schema.properties) return objectType(schema, indent);
  return "unknown";
}
const wrap = (text) => (/[ |&]/.test(text) ? `(${text})` : text);

function objectType(schema, indent) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const inner = indent + "  ";
  const lines = Object.entries(properties).map(([name, value]) => {
    const comment = value?.description ? `${inner}/** ${String(value.description).replace(/\s+/g, " ").slice(0, 160)} */\n` : "";
    return `${comment}${inner}${safeName(name)}${required.has(name) ? "" : "?"}: ${toType(value, inner)};`;
  });
  if (schema.additionalProperties && typeof schema.additionalProperties === "object")
    lines.push(`${inner}[key: string]: ${toType(schema.additionalProperties, inner)};`);
  if (!lines.length) return "Record<string, unknown>";
  return `{\n${lines.join("\n")}\n${indent}}`;
}
const safeName = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));

const header = `// Generated by scripts/generate-sdk-types.mjs from the app's own input checks.
// Do not edit by hand: change the zod schema in src/ and run the script again.

`;

