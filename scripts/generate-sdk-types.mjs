const parts = [header];
for (const [name, schema] of Object.entries(wanted)) {
  const json = z.toJSONSchema(schema, { io: "input", unrepresentable: "any" });
  parts.push(`export interface ${name} ${toType(json)}\n\n`);
}
parts.push(handwritten);

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "packages", "sdk", "types.d.ts");
await writeFile(target, parts.join(""));
console.log(`Wrote ${target} from ${Object.keys(wanted).length} schemas.`);
