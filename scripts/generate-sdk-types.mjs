/**
 * Writes packages/sdk/types.d.ts from the app's own input checks.
 *
 * The app already says, in one place, exactly what every request may contain — the zod schemas in
 * src/. Rather than describing those a second time by hand in the client, this reads them out of
 * the built app, turns each into JSON Schema (zod does that itself), and writes the matching
 * TypeScript. So the types a script sees cannot drift from what the app will actually accept:
 * change a schema, run `node scripts/generate-sdk-types.mjs`, and the types follow.
 *
 * Run it after `npm run build`.
 */
